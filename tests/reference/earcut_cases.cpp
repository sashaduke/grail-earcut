// Generates tests/earcut/cases.grl: polygons as exact binary64 literals and the triangle index
// lists mapbox/earcut.hpp 2.2.4 produces for them. Regenerate with
//   clang++ -std=c++17 -O1 -I<earcut>/include earcut_cases.cpp -o cases && ./cases > ../../earcut/cases.grl
// earcut.hpp uses uint32_t without including <cstdint> itself.
#include <cstdint>
#include <mapbox/earcut.hpp>
#include <array>
#include <cmath>
#include <cstdio>
#include <vector>

using Point = std::array<double, 2>;
using Ring = std::vector<Point>;
using Polygon = std::vector<Ring>;

static uint64_t state = 0x9E3779B97F4A7C15ull;
static double rnd() { // deterministic, in [0, 1)
    state = state * 6364136223846793005ull + 1442695040888963407ull;
    return (double)(state >> 11) / 9007199254740992.0;
}
static Ring circle(double cx, double cy, double r, int n, double jitter, bool reverse) {
    Ring ring;
    for (int i = 0; i < n; ++i) {
        double a = 6.283185307179586 * i / n;
        double rr = r * (1.0 + jitter * (rnd() - 0.5));
        ring.push_back({cx + rr * std::cos(a), cy + rr * std::sin(a)});
    }
    if (reverse) std::vector<Point>(ring.rbegin(), ring.rend()).swap(ring);
    return ring;
}
// A Grail f64 literal: %.17g round-trips binary64, plus ".0" when it would read as an integer.
static void lit(double v) {
    char buf[64];
    std::snprintf(buf, sizeof buf, "%.17g", v);
    bool plain = true;
    for (const char *c = buf; *c; ++c)
        if (*c == '.' || *c == 'e' || *c == 'n' || *c == 'i') plain = false;
    std::printf("%s%s", buf, plain ? ".0" : "");
}
static void emit(const char *name, const Polygon &poly) {
    std::vector<uint32_t> idx = mapbox::earcut<uint32_t>(poly);
    std::printf("    // %s\n    mut %s = f64[][];\n", name, name);
    for (const Ring &ring : poly) {
        std::printf("    %s.push(f64[", name);
        for (size_t i = 0; i < ring.size(); ++i) {
            std::printf("%s", i ? ", " : "");
            lit(ring[i][0]);
            std::printf(", ");
            lit(ring[i][1]);
        }
        std::printf("]);\n");
    }
    std::printf("    bad += check(\"%s\", earcut::triangulate(&%s), u64[", name, name);
    for (size_t i = 0; i < idx.size(); ++i) std::printf("%s%u", i ? ", " : "", idx[i]);
    std::printf("]);\n");
}
int main() {
    std::printf("// Generated by tests/reference/earcut/earcut_cases.cpp from mapbox/earcut.hpp 2.2.4; do not edit.\n");
    std::printf("use earcut;\n\n// Returns 1 when the triangle list differs from the C++ result.\nfn check(name: &[u8], got: u64[], want: u64[]) -> u64 {\n");
    std::printf("    if got.len() != want.len() {\n        println(\"{}: {} indices, expected {}\", name, got.len(), want.len());\n        return 1;\n    }\n");
    std::printf("    for i in got.len() {\n        if got[i] != want[i] {\n            println(\"{}: index {} is {}, expected {}\", name, i, got[i], want[i]);\n            return 1;\n        }\n    }\n");
    std::printf("    println(\"{}: ok ({} triangles)\", name, got.len() / 3);\n    return 0;\n}\n\nfn main() -> u64 {\n    mut bad: u64 = 0;\n");
    emit("square", {{{0, 0}, {10, 0}, {10, 10}, {0, 10}}});
    emit("concave_l", {{{0, 0}, {6, 0}, {6, 2}, {2, 2}, {2, 6}, {0, 6}}});
    emit("square_hole", {{{0, 0}, {10, 0}, {10, 10}, {0, 10}}, {{3, 3}, {3, 7}, {7, 7}, {7, 3}}});
    emit("two_holes", {{{0, 0}, {20, 0}, {20, 10}, {0, 10}}, {{2, 2}, {2, 8}, {8, 8}, {8, 2}}, {{12, 2}, {12, 8}, {18, 8}, {18, 2}}});
    emit("collinear_dupes", {{{0, 0}, {5, 0}, {5, 0}, {10, 0}, {10, 5}, {10, 10}, {5, 10}, {0, 10}, {0, 5}}});
    emit("zero_area", {{{0, 0}, {5, 0}, {10, 0}}});
    Ring star;
    for (int i = 0; i < 20; ++i) {
        double a = 6.283185307179586 * i / 20, r = i % 2 ? 4.0 : 10.0;
        star.push_back({r * std::cos(a), r * std::sin(a)});
    }
    emit("star", {star});
    emit("noisy_circle", {circle(0, 0, 100, 96, 0.3, false)});
    emit("hashed_holes", {circle(0, 0, 100, 120, 0.2, false), circle(-40, 0, 15, 12, 0.2, true),
                          circle(40, 10, 20, 16, 0.2, true), circle(0, -50, 10, 9, 0.1, true)});
    emit("touching_hole", {{{0, 0}, {10, 0}, {10, 10}, {0, 10}}, {{0, 5}, {4, 3}, {4, 7}}});
    std::printf("    return bad;\n}\n");
    return 0;
}
